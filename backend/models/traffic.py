"""
Traffic Event & Aggregated Statistics Models
"""

from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field


class TrafficEventFeatures(BaseModel):
    packet_rate: float = Field(default=0.0, description="Packets per second")
    byte_rate: float = Field(default=0.0, description="Bytes per second")
    conn_freq: float = Field(default=0.0, description="Connections per 10 seconds")
    syn_ratio: float = Field(default=0.0, ge=0.0, le=1.0, description="Ratio of TCP SYN packets")
    payload_entropy: float = Field(default=0.0, ge=0.0, le=8.0, description="Shannon entropy of packet payload")
    flow_duration: float = Field(default=1.0, ge=0.0, description="Flow window duration in seconds")
    unique_dest_ips: Optional[int] = Field(default=1, ge=1, description="Distinct destination IPs contacted")
    avg_packet_size: Optional[float] = Field(default=128.0, ge=0.0, description="Average packet size in bytes")
    outbound_ratio: Optional[float] = Field(default=0.5, ge=0.0, le=1.0, description="Outbound to inbound ratio")
    rst_ratio: Optional[float] = Field(default=0.0, ge=0.0, le=1.0, description="TCP RST ratio")
    dns_query_rate: Optional[float] = Field(default=0.0, ge=0.0, description="DNS queries per second")
    failed_connections: Optional[int] = Field(default=0, ge=0, description="Count of failed connection attempts")


class TrafficEventModel(BaseModel):
    flow_id: str = Field(..., description="Unique flow identifier e.g. FLW-104920")
    timestamp: str = Field(..., description="Timestamp in HH:MM:SS or ISO format")
    device_id: str = Field(..., description="Source IoT hardware ID")
    device_name: str = Field(default="IoT Device", description="Descriptive asset name")
    source_ip: str = Field(..., description="Source IP address")
    dest_ip: str = Field(..., description="Destination IP address")
    source_port: Optional[int] = Field(default=None, ge=1, le=65535, description="Source port")
    dest_port: int = Field(..., ge=1, le=65535, description="Destination network port")
    protocol: str = Field(default="TCP", description="L4/L7 protocol: TCP, UDP, MQTT, RTSP, CoAP, etc.")
    direction: Optional[str] = Field(default="outbound", description="Flow direction: inbound, outbound, lateral, internal")
    status: str = Field(default="Normal", description="Classification: Normal, Suspicious, High-Risk")
    data_source: str = Field(default="collector", description="Data provenance: collector, demo_scenario, synthetic_tick")
    is_demo: bool = Field(default=False, description="True if generated by demo scenario, False for real collector")
    collector_id: Optional[str] = Field(default="collector-primary", description="Sensor/collector probe ID")
    collector_type: Optional[str] = Field(default="netflow_ipfix", description="Collector type: netflow_ipfix, zeek, agent_probe, demo")
    flow_hash: Optional[str] = Field(default=None, description="Idempotency hash of the flow event")
    packet_count: Optional[int] = Field(default=10, ge=1, description="Total packet count in flow")
    byte_count: Optional[int] = Field(default=500, ge=1, description="Total byte count in flow")
    duration_sec: Optional[float] = Field(default=1.0, ge=0.0, description="Flow duration in seconds")
    raw_features: Optional[TrafficEventFeatures] = None
    rule_matches: List[Dict[str, Any]] = Field(default_factory=list)
    ml_prediction: Optional[Dict[str, Any]] = None

    def to_mongo_dict(self) -> Dict[str, Any]:
        return self.model_dump()


class AggregatedTrafficStats(BaseModel):
    timeframe: str = Field(default="24h", description="Aggregation timeframe: 1h, 6h, 24h, 7d")
    timestamp: str = Field(..., description="Snapshot timestamp")
    total_flows: int = Field(default=0, ge=0)
    malicious_ratio_pct: float = Field(default=0.0, ge=0.0, le=100.0)
    active_strains_count: int = Field(default=0, ge=0)
    peak_incursion_mbps: float = Field(default=0.0, ge=0.0)
    health_score: int = Field(default=100, ge=0, le=100)
    protocol_breakdown: List[Dict[str, Any]] = Field(default_factory=list)
    top_attacked_ports: List[Dict[str, Any]] = Field(default_factory=list)
    geographic_threats: List[Dict[str, Any]] = Field(default_factory=list)
